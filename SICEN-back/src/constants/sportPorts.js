export const SPORT_PORT_SECTOR_LABELS = {
  "rio-plata-superior": "Río de la Plata superior (20 MN)",
  "rio-plata-inferior": "Río de la Plata inferior (15 MN)",
};

export const SPORT_PORT_SECTOR_ORDER = [
  "rio-plata-superior",
  "rio-plata-inferior",
];

export const SPORT_PORTS_BY_ID = new Map(SPORT_PORTS.map((p) => [p.id, p]));

export function sportPortsBySector() {
  const groups = {};
  for (const sector of SPORT_PORT_SECTOR_ORDER) groups[sector] = [];
  for (const port of SPORT_PORTS) {
    if (!groups[port.sector]) groups[port.sector] = [];
    groups[port.sector].push(port);
  }
  return groups;
}

export function getSportPortById(id) {
  if (!id) return null;
  return SPORT_PORTS_BY_ID.get(String(id)) ?? null;
}
